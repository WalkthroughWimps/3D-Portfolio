import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const mode = process.argv[2] || 'check';
if (!['write', 'check'].includes(mode)) throw new Error('Usage: node tools/prepare-site-html.mjs write|check');
const manifest = JSON.parse(await readFile(resolve(root, 'data/runtime-dependencies.json'), 'utf8'));
const fragment = (await readFile(resolve(root, '_7-shared-scripts/header.html'), 'utf8')).trim()
  .replace(/\s*<\?xml[^>]*\?>/g, '');
const START = '<!-- site-header:generated:start -->';
const END = '<!-- site-header:generated:end -->';
const MAP_START = '<!-- runtime-importmap:generated:start -->';
const MAP_END = '<!-- runtime-importmap:generated:end -->';
const generated = (start, end, value) => `${start}\n${value}\n${end}`;
let failures = [];
for (const [file, dep] of Object.entries(manifest.three.routes)) {
  const target = resolve(root, file);
  const original = await readFile(target, 'utf8');
  let updated = original;
  const base = `${dep.origin}/three@${dep.version}/`;
  const map = generated(MAP_START, MAP_END, `    <script type="importmap">\n${JSON.stringify({ imports: { three: `${base}build/three.module.js`, 'three/addons/': `${base}examples/jsm/` } }, null, 2).split('\n').map(line => `    ${line}`).join('\n')}\n    </script>`);
  if (updated.includes(MAP_START)) {
    updated = updated.replace(new RegExp(`${MAP_START}[\\s\\S]*?${MAP_END}`), map);
  } else {
    const match = updated.match(/<script type="importmap">[\s\S]*?<\/script>/);
    if (!match) throw new Error(`Missing import map in ${file}`);
    updated = updated.replace(match[0], map);
  }
  if (file !== 'index.html') {
    const skipTarget = { '_4-games/games.html': 'model-stage', '_6-docs/docs.html': 'glb-viewer' }[file] || 'page-main';
    const pageHeader = fragment.replace('href="#page-main"', `href="#${skipTarget}"`)
      .replace(/<a ([^>]*href="([^"]+)"[^>]*)>/g, (tag, attributes, href) =>
        !href.startsWith('#') && new URL(href, `https://site.invalid/${file}`).pathname === `/${file}`
          ? `<a ${attributes} aria-current="page">` : tag);
    const header = generated(START, END, pageHeader);
    if (updated.includes(START)) updated = updated.replace(new RegExp(`${START}[\\s\\S]*?${END}`), header);
    else updated = updated.replace(/<div id="header-placeholder"><\/div>(?:\s*<!-- Placeholder for header -->)?/, `<div id="header-placeholder">\n${header}\n</div>`);
    if (!updated.includes(START)) throw new Error(`Missing header placeholder in ${file}`);
  }
  if (updated !== original) {
    if (mode === 'write') await writeFile(target, updated);
    else failures.push(file);
  }
}
const config = `// Generated by tools/prepare-site-html.mjs from data/runtime-dependencies.json.\nself.SITE_WORKER_ASSET_CONFIG = ${JSON.stringify({ introAssetKey: manifest.introAssetKey, defaultAssetOrigin: manifest.defaultAssetOrigin })};\n`;
const workerPath = resolve(root, 'sw-asset-config.js');
const workerOriginal = await readFile(workerPath, 'utf8').catch(() => '');
if (config !== workerOriginal) {
  if (mode === 'write') await writeFile(workerPath, config);
  else failures.push('sw-asset-config.js');
}
if (failures.length) { console.error(`Generated output differs: ${failures.join(', ')}`); process.exitCode = 1; }
else console.log(`Site HTML and worker config ${mode === 'write' ? 'written' : 'current'}.`);
